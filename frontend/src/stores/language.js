export const useLanguageStore = defineStore('language', () => {
  const current = ref(localStorage.getItem('lang') || 'uz')

  const languages = [
    { code: 'uz', label: "O'zbekcha", flag: '🇺🇿' },
    { code: 'en', label: 'English', flag: '🇬🇧' },
    { code: 'ru', label: 'Русский', flag: '🇷🇺' },
  ]

  const currentLang = computed(() => languages.find(l => l.code === current.value))

  function setLanguage(code) {
    current.value = code
    localStorage.setItem('lang', code)
  }

  function t(key) {
    return translations[current.value]?.[key] || translations['uz']?.[key] || key
  }

  return { current, languages, currentLang, setLanguage, t }
})